// --- Shared transform: raw (requirement + nested evidence) rows -> {bidders, requirements, evidence, results} ---
// Requirement/Evidence/Result field names below follow the sync format agreed
// across teams (Requirement JSON / Evidence JSON / Result JSON).
function buildTenderData(rawRows) {
    const bidderMap = new Map();
    rawRows.forEach((item) => {
        if (!bidderMap.has(item.evidence.bidder_id)) {
            bidderMap.set(item.evidence.bidder_id, {
                bidder_id: item.evidence.bidder_id,
                name: item.evidence.bidder_name,
            });
        }
    });
    const bidders = [...bidderMap.values()];

    const requirementMap = new Map();
    rawRows.forEach((item) => {
        if (!requirementMap.has(item.requirement_id)) {
            requirementMap.set(item.requirement_id, {
                requirement_id: item.requirement_id,
                name: item.requirement,
                category: item.category,
                operator: item.operator,
                required_value: item.required_value,
                unit: item.req_unit,
                source: { clause: item.clause, page: item.clause_page },
            });
        }
    });
    const requirements = [...requirementMap.values()];

    const evidence = rawRows.map((item) => {
        const { bidder_name, ...rest } = item.evidence;
        return rest;
    });

    const results = rawRows.map((item) => ({
        bidder_id: item.evidence.bidder_id,
        requirement_id: item.requirement_id,
        status: item.status,
        required: item.required,
        found: item.found,
        reason: item.evidence.evidence_text,
    }));

    return { bidders, requirements, evidence, results };
}

